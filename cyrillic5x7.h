// Попіксельне малювання символу
void drawCyrillicChar(Adafruit_GFX &gfx, int index, int16_t x, int16_t y, uint8_t size) {
  for (int col = 0; col < 5; col++) {
    uint8_t line = pgm_read_byte(&cyrillic5x7Bitmaps[index][col]);
    for (int row = 0; row < 7; row++) {
      if (line & (1 << row)) {
        if (size == 1) {
          gfx.drawPixel(x + col, y + row, SSD1306_WHITE);
        } else {
          gfx.fillRect(x + col * size, y + row * size, size, size, SSD1306_WHITE);
        }
      }
    }
  }
}

// Друк текстового рядка
void printCyrillic(Adafruit_GFX &gfx, String text, int16_t x, int16_t y, uint8_t size = 1) {
  int16_t curX = x;
  int16_t curY = y;

  for (size_t i = 0; i < text.length(); i++) {
    uint8_t c = text[i];

    if (c == '\n') {
      curX = x;
      curY += 8 * size;
      continue;
    }

    if (c == 0xD0 || c == 0xD1) {
      i++;
      if (i >= text.length()) break;
      uint8_t c2 = text[i];
      int index = 0;

      if (c == 0xD0 && c2 >= 0x90 && c2 <= 0xAF) index = (c2 - 0x90) + 1;       // А-Я
      else if (c == 0xD0 && c2 >= 0xB0 && c2 <= 0xBF) index = (c2 - 0xB0) + 1; // а-п
      else if (c == 0xD1 && c2 >= 0x80 && c2 <= 0x8F) index = (c2 - 0x80) + 17;// р-я
      else if (c == 0xD0 && (c2 == 0x86 || c2 == 0x87)) index = 9;             // І, Ї
      else if (c == 0xD1 && (c2 == 0x96 || c2 == 0x97)) index = 9;             // і, ї
      else if (c == 0xD0 && c2 == 0x84) index = 6;                             // Є
      else if (c == 0xD1 && c2 == 0x94) index = 6;                             // є

      if (index >= 1 && index <= 32) {
        drawCyrillicChar(gfx, index, curX, curY, size);
      } else {
        drawCyrillicChar(gfx, 0, curX, curY, size);
      }
      curX += 6 * size;
    } else {
      gfx.setTextSize(size);
      gfx.setCursor(curX, curY);
      gfx.write(c);
      curX += 6 * size;
    }
  }
}

